# Copia SOMENTE os sprites usados pelo jogo, a partir do jogo instalado do usuário (extraídos com UnityPy), para uso LOCAL.
import json,os,shutil,re
J=lambda n:json.load(open(f'json/{n}.json',encoding='utf-8'))
W=J(16545584); EN=J(16783184); CH=J(17537508); PK=J(17489200)
OUT=r'D:\jogos\vampire-like\assets'
if os.path.exists(OUT): shutil.rmtree(OUT)
for d in ['chars','portraits','enemies','icons','fx','ui','fonts','bg']: os.makedirs(f'{OUT}/{d}')
art={'chars':{},'portraits':{},'enemies':{},'icons':{},'fx':{},'missing':[]}
def cp(src,dst):
    if os.path.exists(src): shutil.copy(src,dst); return True
    art['missing'].append(src); return False
CHB={'ANTONIO':'antonio','IMELDA':'imelda','GENNARO':'gennaro','CIRO':'arca','PORTA':'porta','LAMA':'lama','CAMILLO':'poe','DOMMARIO':'dommario','CROCI':'krochi'}
for cid,b in CHB.items():
    c=CH[cid][0]; base=c['spriteName'].replace('_01.png','')   # ex.: newAntonio
    n=c['walkingFrames']; ok=[]
    for i in range(1,n+1):
        if cp(f'raw2/character_{b}/{base}_{i:02d}.png',f'{OUT}/chars/{cid}_{i}.png'): ok.append(f'assets/chars/{cid}_{i}.png')
    art['chars'][cid]=ok
    pn={'CAMILLO':'p_poe','CIRO':'p_arca','CROCI':'p_croci'}.get(cid,'p_'+b)
    for cand in (pn,'p_'+b):
        if os.path.exists(f'raw/sprites/{cand}.png'): shutil.copy(f'raw/sprites/{cand}.png',f'{OUT}/portraits/{cid}.png'); art['portraits'][cid]=f'assets/portraits/{cid}.png'; break
# inimigos: frames idle <Base>_i01..i04 (evidência: nomes dos sprites nos bundles enemies/enemies_universal)
ids=set()
for w in J(17148800)['FOREST']: ids.update(w.get('enemies',[])+w.get('bosses',[]))
for eid in sorted(ids):
    v=EN[eid][0] if isinstance(EN[eid],list) else EN[eid]; bases=[]
    for fn in v['frameNames']:
        base=re.sub(r'_\d+\.png$','',fn); frames=[]
        for i in range(1,5):
            for bundle in ('enemies','enemies_universal','enemies2'):
                s=f'raw2/{bundle}/{base}_i{i:02d}.png'
                if os.path.exists(s): shutil.copy(s,f'{OUT}/enemies/{base}_{i}.png'); frames.append(f'assets/enemies/{base}_{i}.png'); break
        if not frames:
            for bundle in ('enemies','enemies_universal','enemies2'):
                s=f'raw2/{bundle}/{base}_0.png'
                if os.path.exists(s): shutil.copy(s,f'{OUT}/enemies/{base}_1.png'); frames=[f'assets/enemies/{base}_1.png']; break
        if frames: bases.append(frames)
        else: art['missing'].append('enemy:'+base)
    art['enemies'][eid]={'variants':bases,'scale':v.get('scale',1)}
# ícones de armas/passivos (frameName do JSON)
for k,defs in W.items():
    fn=defs[0].get('frameName')
    if fn and not os.path.exists(f'{OUT}/icons/{fn}'):
        if cp(f'raw/sprites/{fn}',f'{OUT}/icons/{fn}'): art['icons'][k]=f'assets/icons/{fn}'
    elif fn: art['icons'][k]=f'assets/icons/{fn}'
for k in ['HOLYBOOK','VESPERS']: pass
# efeitos / projéteis / pickups (escolha de mapeamento = DESIGN; sprites reais do jogo)
fx={'whip':'slash.png','whip2':'slash_sword.png','knife':'ProjectileKnife3.png','knife2':'ProjectileKnife1.png','wand':'ProjectileFlameBlue.png','wand2':'ProjectileHoly1.png','axe':'ProjectileAxe1.png','scythe':'ProjectileScythe.png','cross':'ProjectileCross1.png','sword':'ProjectileSword.png','book':'HolyBook.png','unholybook':'UnholyBook.png','fire':'ProjectileFireball.png','hellfire':'ProjectileHellfireLarge.png','light1':'Lightning1.png','light2':'Lightning2.png','light3':'Lightning3.png','lightring':'Rings1.png','shadow':'ShadowSpot.png','gemb':'GemBlue.png','gemg':'GemGreen.png','gemr':'GemRed.png','coin':'CoinGold.png','silf1':'Silf1.png','silf2':'Silf2.png','silf3':'Silf3.png','laurel':'Laurel.png','bottle':'ProjectileBottle.png','spin':'ProjectileSpin.png','flare1':'FlareStar1.png','flare3':'FlareStar3.png','flare5':'FlareStar5.png','sharpstar':'blurredSharpStar.png','ring2':'Circle2.png','ring3':'Circle3.png','ring4':'Circle4.png','magiccircle':'MagicCircleRed.png','wing':'Wing.png','hit':'HitStarWhite1.png','hit2':'HitWhite1.png','garlic':'Garlic.png'}
for i in range(1,9): fx[f'chest{i}']=f'TreasureIdle_{i:02d}.png'
for k,fn in fx.items():
    if cp(f'raw/sprites/{fn}',f'{OUT}/fx/{fn}'): art['fx'][k]=f'assets/fx/{fn}'
for fn in ['frameB.png','frameB_gold.png','frameB10.png','frameB_sotn.png','frameB_red.png','button_c9_normal.png','frame5_c4.png','frameB9.png']:
    cp(f'raw2/ui_menu/{fn}',f'{OUT}/ui/{fn}')
cp('raw2/bg_forest/bg_forest.png',f'{OUT}/bg/forest.png')
cp('raw/fonts/PerfectDOSVGA437.ttf',f'{OUT}/fonts/PerfectDOSVGA437.ttf')
open(r'D:\jogos\vampire-like\art.js','w',encoding='utf-8').write('// GENERATED by _evidence/build_assets.py. Mapeamento de arte (sprites copiados do jogo instalado, uso local).\nconst __a='+json.dumps(art,indent=1)+';\nif(typeof window!=="undefined")window.ART=__a;else module.exports=__a;\n')
tot=sum(os.path.getsize(os.path.join(r,f)) for r,_,fs in os.walk(OUT) for f in fs)
print('assets bytes',tot,'missing',art['missing'])
print({k:len(v) for k,v in art.items()})
